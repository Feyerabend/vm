#!/usr/bin/env python3
"""
Write the four limit tests into suite/. They are long and repetitive,
so they are generated rather than typed. Run it again only if the
limits in SPEC.md change.
"""

STACK = 256
FRAMES = 256


def write(name, lines, expect):
    with open(f"suite/{name}.asm", "w") as f:
        f.write("\n".join(lines) + "\n")
    with open(f"suite/{name}.expect", "w") as f:
        f.write(expect)


def stack(name, dups, expect):
    lines = [f"; Fill the stack with 1 + {dups} values (generated by makelimits.py).",
             "        PUSH 7"]
    lines += ["        DUP"] * dups
    lines += ["        PRINT", "        HALT"]
    write(name, lines, expect)


def frames(name, depth, expect):
    lines = [f"; Calls nested {depth} deep (generated by makelimits.py).",
             "main:   CALL f0 0",
             "        PRINT",
             "        HALT"]
    for i in range(depth - 1):
        lines += [f"f{i}:    CALL f{i + 1} 0", "        RET"]
    lines += [f"f{depth - 1}:    PUSH 1", "        RET"]
    write(name, lines, expect)


stack("limit-stack", STACK - 1, "7\nstatus 0\n")
stack("trap-stack-overflow", STACK, f"status 1\ntrap: stack overflow at {2 + STACK - 1}\n")
frames("limit-frames", FRAMES, "1\nstatus 0\n")
frames("trap-too-deep", FRAMES + 1, f"status 1\ntrap: too many nested calls at {5 + 4 * (FRAMES - 1)}\n")
